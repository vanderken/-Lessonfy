CREATE TABLE core_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      VARCHAR(128)  NOT NULL,
    last_login    TIMESTAMPTZ   NULL,
    is_superuser  BOOLEAN       NOT NULL DEFAULT FALSE,
    first_name    VARCHAR(150)  NOT NULL DEFAULT '',
    last_name     VARCHAR(150)  NOT NULL DEFAULT '',
    is_staff      BOOLEAN       NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    date_joined   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    email         VARCHAR(254)  NOT NULL UNIQUE
);

CREATE UNIQUE INDEX user_email_unique_ci ON core_user (LOWER(email));

CREATE TABLE core_usersettings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT           NOT NULL UNIQUE REFERENCES core_user(id) ON DELETE CASCADE,
    font_size      SMALLINT         NOT NULL DEFAULT 19 CHECK (font_size >= 0),
    line_spacing   DOUBLE PRECISION NOT NULL DEFAULT 1.7,
    theme          VARCHAR(10)      NOT NULL DEFAULT 'light',
    background     VARCHAR(10)      NOT NULL DEFAULT 'default',
    bionic_reading BOOLEAN          NOT NULL DEFAULT TRUE,
    focus_mode     BOOLEAN          NOT NULL DEFAULT TRUE,
    sound          VARCHAR(20)      NOT NULL DEFAULT 'off',
    volume         DOUBLE PRECISION NOT NULL DEFAULT 0.4,
    timer_preset   VARCHAR(10)      NOT NULL DEFAULT '25-5',
    CONSTRAINT usersettings_font_size_range    CHECK (font_size BETWEEN 12 AND 32),
    CONSTRAINT usersettings_line_spacing_range CHECK (line_spacing BETWEEN 1.0 AND 3.0),
    CONSTRAINT usersettings_volume_range       CHECK (volume BETWEEN 0.0 AND 1.0),
    CONSTRAINT usersettings_theme_valid        CHECK (theme IN ('light','dark')),
    CONSTRAINT usersettings_background_valid   CHECK (background IN ('default','cream','mint','sky')),
    CONSTRAINT usersettings_sound_valid        CHECK (sound IN ('off','brown','white','rain')),
    CONSTRAINT usersettings_timer_valid        CHECK (timer_preset IN ('15-3','25-5','45-10'))
);

CREATE TABLE core_collection (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES core_user(id) ON DELETE CASCADE,
    name       VARCHAR(100) NOT NULL,
    color      VARCHAR(7)   NOT NULL DEFAULT '#FFD166',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX core_collection_user_id_idx ON core_collection (user_id);
CREATE UNIQUE INDEX collection_unique_name_per_user ON core_collection (LOWER(name), user_id);

CREATE TABLE core_lesson (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES core_user(id) ON DELETE CASCADE,
    title       VARCHAR(200) NOT NULL,
    subtitle    VARCHAR(200) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX core_lesson_user_id_idx ON core_lesson (user_id);

CREATE TABLE core_panel (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id  BIGINT  NOT NULL REFERENCES core_lesson(id) ON DELETE CASCADE,
    "order"    INTEGER NOT NULL CHECK ("order" >= 0),
    text       TEXT    NOT NULL,
    is_done    BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT panel_unique_order_per_lesson UNIQUE (lesson_id, "order")
);

CREATE TABLE core_pin (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    panel_id      BIGINT       NOT NULL REFERENCES core_panel(id) ON DELETE CASCADE,
    collection_id BIGINT       NOT NULL REFERENCES core_collection(id) ON DELETE CASCADE,
    start_offset  INTEGER      NOT NULL CHECK (start_offset >= 0),
    end_offset    INTEGER      NOT NULL CHECK (end_offset >= 0),
    text_snippet  VARCHAR(500) NOT NULL,
    resolved      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pin_end_after_start CHECK (end_offset > start_offset)
);
CREATE INDEX core_pin_panel_id_idx      ON core_pin (panel_id);
CREATE INDEX core_pin_collection_id_idx ON core_pin (collection_id);
